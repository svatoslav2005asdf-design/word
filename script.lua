end

local function IsAvailable(word)
    local normalized = Canonical(word)
    return not Features.MatchWords[normalized] and not Used[normalized] and not Rejected[normalized] and not Tried[normalized] and not RoundWords[normalized]
end

local function Estimate(length)
    local errors = Features.Legit and math.min(math.floor(Features.Number("LegitErrors", "Errors", 0, 10)), length - 1) or 0
    local delay = Features.Legit and Features.Number("LegitDelay", "Delay", 0, 20) or 0
    return delay + (length - 1 + errors * 2) / GetSpeed() + errors * 0.5 + 0.05
end

local function CandidatePool(letter, seconds)
    local index = Dictionary[letter]
    if not index then
        return {}
    end
    local pool = {}
    if Mode == "Common" then
        for _, word in ipairs(CommonWords) do
            if utf8.len(word) >= 6 and utf8.len(word) <= 10 and FirstLetter(word) == letter and IsAvailable(word) and Estimate(utf8.len(word)) <= seconds then
                table.insert(pool, word)
            end
        end
        if #pool > 0 then
            return pool
        end
    end
    local startLength, endLength, step = 2, 5, 1
    if Mode == "Ultra Longest" then
        startLength, endLength, step = 21, 16, -1
    elseif Mode == "Longest" then
        startLength, endLength, step = 15, 11, -1
    elseif Mode == "Common" then
        startLength, endLength = 6, 10
    end
    for length = startLength, endLength, step do
        if Estimate(length) <= seconds then
            for _, word in ipairs(index[length] or {}) do
                if IsAvailable(word) then
                    table.insert(pool, word)
                end
            end
            if #pool > 0 and Mode ~= "Common" then
                break
            end
        end
    end
    return pool
end

